package model;

/**
 * Enum representing the types of bread available for sandwiches and burgers.
 *
 * Each bread type provides a different flavor and texture option for menu items.
 *
 * Used in combination with menu items such as Sandwich and Burger.
 *
 * Available bread options include Brioche, Wheat, Pretzel, Bagel, and Sourdough.
 *
 * @author Marco Ferreira
 * @author Sathish Kosalram
 */
public enum Bread {
    BRIOCHE,
    WHEAT,
    PRETZEL,
    BAGEL,
    SOURDOUGH
}
